#!/usr/bin/env python3
"""Era III (Etched, 16-bit rich palette) battle sprites for the Era III post-game region
Quillmarch: its starting set and first batch (data/eras.json). Original designs, generated by this script.

    python3 tools/art/gen_era3.py              write art/era3/spirlings/<id>_front.png / _back.png
    python3 tools/art/gen_era3.py --check      only verify art/era3/spirlings/ (exit 1 on a problem)
    python3 tools/art/gen_era3.py --sheet P    also write a contact sheet to P
    python3 tools/art/gen_era3.py --lines REGION [--sheet P]
        draw the region's other lines (tools/art/lines/REGION.py, gen_lines.py body plans) in Era III

Rules (data/eras.json "era3"): 64 x 64, at most 15 tones per sprite, light from the top left,
coloured outline (darkest tone of the part's own material, never black), fur / scale / feather
textures, and every stage of a line built from the same parts so the stages look alike.
Each part is an ellipsoid (optionally rotated); its tone comes from a Lambert term against the
light direction, quantised to the 5 tones of its material, then nudged by the texture pattern.
"""
from __future__ import annotations

import json
import math
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DATA = json.load(open(os.path.join(ROOT, "data", "eras.json"), encoding="utf-8"))["era3"]
DST = os.path.join(ROOT, "art", "era3", "spirlings")
S = DATA["sprite_size"]
_l = DATA["light_dir"]
_n = math.sqrt(sum(c * c for c in _l))
LIGHT = tuple(c / _n for c in _l)
MATS = {k: [tuple(int(h[i:i + 2], 16) for i in (0, 2, 4)) for h in v] for k, v in DATA["materials"].items()}


class Part:
    def __init__(self, cx, cy, rx, ry, mat, rot=0.0, tex=True, face=False):
        self.cx, self.cy, self.rx, self.ry, self.mat, self.rot, self.tex, self.face = cx, cy, rx, ry, mat, rot, tex, face

    def normal(self, x: float, y: float):
        dx, dy = x - self.cx, y - self.cy
        c, s = math.cos(self.rot), math.sin(self.rot)
        u, v = (dx * c + dy * s) / self.rx, (-dx * s + dy * c) / self.ry
        d = u * u + v * v
        if d > 1.0:
            return None
        nz = math.sqrt(1.0 - d)
        # back to screen space
        nx, ny = u * c - v * s, u * s + v * c
        return nx, ny, nz


def tone(n, tex: str, x: int, y: int, use_tex: bool) -> int:
    i = n[0] * LIGHT[0] + n[1] * LIGHT[1] + n[2] * LIGHT[2]
    t = 4 if i > 0.93 else 3 if i > 0.62 else 2 if i > 0.22 else 1
    if use_tex and 1 < t < 4:
        if tex == "fur" and (x * 2 + y) % 7 == 0:
            t -= 1
        elif tex == "scale" and ((y % 4 == 0 and x % 4 != 2) or (y % 4 == 2 and x % 4 == 0)):
            t -= 1
        elif tex == "feather" and (x + abs((y % 6) - 3)) % 5 == 0:
            t -= 1
    return t


def parts_for(line: str, stage: int) -> tuple[list, list]:
    """Parts back to front, plus eye positions (x, y, r). Facing left. Stage 1..3."""
    k = (0.62, 0.81, 1.0)[stage - 1]
    ox, base = 34, 61

    def P(cx, cy, rx, ry, mat, rot=0.0, **kw):
        return Part(ox + cx * k, base - (base - cy) * k if False else base + (cy - base) * k, rx * k, ry * k, mat, rot, **kw)

    ps, eyes = [], []
    if line == "vesk":
        for t in range(stage):  # one tail per stage
            ps.append(P(16 + 2 * t, 40 - 6 * t, 9, 16, "gale_fur", 0.7 - 0.35 * t))
            ps.append(P(19 + 2 * t, 30 - 6 * t, 4, 5, "gale_belly", 0.7 - 0.35 * t))
        ps.append(P(2, 50, 4, 10, "gale_fur"))
        ps.append(P(4, 44, 15, 12, "gale_fur"))
        ps.append(P(-2, 48, 9, 7, "gale_belly"))
        ps.append(P(-8, 52, 4, 9, "gale_fur"))
        ear = 9 + 3 * stage
        ps.append(P(-10, 22 - stage, 4, ear, "gale_fur", -0.35))
        ps.append(P(-20, 23 - stage, 4, ear, "gale_fur", 0.25))
        if stage == 3:
            ps.append(P(-6, 38, 12, 8, "gale_belly"))
        ps.append(P(-14, 32, 12, 10, "gale_fur", face=True))
        ps.append(P(-23, 36, 6, 4, "gale_belly", face=True))
        eyes.append((-16, 31, 2.4))
    elif line == "silt":
        ps.append(P(18, 50, 16, 5, "tide_scale", 0.25))
        for i in range(2 + stage):
            ps.append(P(10 - 7 * i, 36 - (stage - 1) * 2, 4, 6 + 2 * stage, "tide_fin", 0.15 * i, tex=False))
        ps.append(P(10, 54, 4, 7, "tide_scale"))
        ps.append(P(2, 46, 17, 10, "tide_scale"))
        ps.append(P(-6, 55, 4, 7, "tide_scale"))
        ps.append(P(-2, 50, 10, 4, "tide_fin", tex=False))
        if stage >= 2:
            ps.append(P(-25, 46, 6, 2.5, "tide_fin", 0.5, tex=False))
        if stage == 3:
            ps.append(P(-26, 34, 7, 2.5, "tide_fin", -0.6, tex=False))
        ps.append(P(-17, 40, 11, 8, "tide_scale", face=True))
        eyes.append((-19, 37, 2.6))
    elif line == "nib":
        # Quill hedgehog: quills fan out of the back, one more per stage, and grow longer.
        n = 5 + 2 * stage
        for i in range(n):
            a = -1.15 + 2.3 * i / (n - 1)
            ln = 7 + 2.5 * stage
            ps.append(P(6 + math.sin(a) * 13, 44 - math.cos(a) * 10, 2.4, ln, "nib_quill", a))
        ps.append(P(10, 57, 4, 4, "nib_face", tex=False))
        ps.append(P(-6, 57, 4, 4, "nib_face", tex=False))
        ps.append(P(5, 47, 16, 11, "nib_quill"))
        ps.append(P(-3, 52, 10, 5, "nib_face"))
        if stage == 3:
            for i in range(3):
                ps.append(P(-12 + 4 * i, 36 - i, 1.8, 6, "nib_quill", -0.5 + 0.3 * i))
        ps.append(P(-15, 46, 9, 8, "nib_face", face=True))
        ps.append(P(-24, 49, 4.5, 3, "nib_face", 0.2, face=True))
        ps.append(P(-28, 49, 1.6, 1.6, "nib_quill", tex=False, face=True))
        eyes.append((-17, 44, 2.0))
    elif line == "filig":
        # Lace moth: etched wings with eye spots, the wings and antenna plumes grow with each stage.
        w = 1.0 + 0.12 * (stage - 1)
        ps.append(P(-4, 22, 6 * w, 15 * w, "lace_wing", -0.25))  # far fore wing
        ps.append(P(14, 26, 8 * w, 19 * w, "lace_wing", 0.95))
        ps.append(P(15, 45, 6 * w, 12 * w, "lace_wing", 1.75))
        ps.append(P(17, 24, 2.6, 2.6, "lace_body", tex=False))
        if stage >= 2:
            ps.append(P(22, 30, 1.8, 1.8, "lace_body", tex=False))
        if stage == 3:
            ps.append(P(25, 55, 2.2, 8, "lace_wing", 0.9, tex=False))
        ps.append(P(8, 48, 5, 9, "lace_body", 0.9))
        ps.append(P(2, 44, 5, 6, "lace_body", 0.9))
        ps.append(P(-4, 39, 6, 7, "lace_body"))
        for i in range(2):
            ps.append(P(-14 + 5 * i, 18, 1.0 + 0.8 * (stage - 1), 7, "lace_wing", -0.5 + 0.3 * i, tex=False))
        ps.append(P(-11, 29, 6.5, 6, "lace_body", face=True))
        eyes.append((-14, 28, 2.4))
    else:  # cindr
        for i in range(stage + 1):
            ps.append(P(18, 46 - 5 * i, 12, 3.5, "ember_feath", -0.3 - 0.25 * i))
        ps.append(P(2, 58, 2, 4, "ember_crest", tex=False))
        ps.append(P(-6, 58, 2, 4, "ember_crest", tex=False))
        ps.append(P(2, 44, 14, 13, "ember_feath"))
        ps.append(P(-4, 48, 8, 8, "ember_crest"))
        ps.append(P(8, 42, 10, 7, "ember_feath", 0.35))
        for i in range(stage):
            ps.append(P(-9 + 3 * i, 18 - 2 * i, 2.5, 7 + 2 * stage, "ember_crest", 0.3 + 0.35 * i, tex=False))
        ps.append(P(-10, 28, 9, 9, "ember_feath", face=True))
        ps.append(P(-20, 30, 5, 2.5, "ember_crest", 0.15, tex=False, face=True))
        eyes.append((-12, 26, 2.2))
    return ps, eyes


def render(sp: dict, back: bool) -> Image.Image:
    ps, eyes = parts_for(sp["line"], sp["stage"])
    if back:
        ps = [p for p in ps if not p.face] + [p for p in ps if p.face]
    grid = [[None] * S for _ in range(S)]  # (mat, tone, part index)
    for pi, p in enumerate(ps):
        for y in range(S):
            for x in range(S):
                n = p.normal(x + 0.5, y + 0.5)
                if n is not None:
                    grid[y][x] = (p.mat, tone(n, sp["texture"], x, y, p.tex), pi)
    out = [[None] * S for _ in range(S)]
    for y in range(S):
        for x in range(S):
            g = grid[y][x]
            if g is None:
                continue
            mat, t, pi = g
            edge = False
            inner = False
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                xx, yy = x + dx, y + dy
                o = grid[yy][xx] if 0 <= xx < S and 0 <= yy < S else None
                if o is None:
                    edge = True
                elif o[2] > pi and o[0] != mat and (dx, dy) in ((1, 0), (0, 1)):
                    inner = True
            out[y][x] = (mat, 0 if edge else max(1, t - 1) if inner else t)
    if not back:
        for ex, ey, r in eyes:
            k = (0.62, 0.81, 1.0)[sp["stage"] - 1]
            cx, cy = 34 + ex * k, 61 + (ey - 61) * k
            rr = max(1.4, r * (0.85 + 0.15 * k))
            head = out[int(cy)][int(cx)][0]
            for y in range(S):
                for x in range(S):
                    if (x + 0.5 - cx) ** 2 + (y + 0.5 - cy) ** 2 <= rr * rr:
                        out[y][x] = (head, 0)
            out[int(cy - rr * 0.5)][int(cx - rr * 0.4)] = (head, 4)
    img = Image.new("RGBA", (S, S))
    px = img.load()
    for y in range(S):
        for x in range(S):
            c = out[y][x]
            sx = S - 1 - x if back else x
            sy = y + 4 if back else y  # back sprites sit lower, bottom edge cropped
            if c is not None and sy < S:
                px[sx, sy] = MATS[c[0]][c[1]] + (255,)
    return img


def problems(img: Image.Image) -> list[str]:
    cols = {c for c in img.getdata() if c[3] > 0}
    out = []
    if img.size != (S, S):
        out.append("size %s" % (img.size,))
    if len(cols) > DATA["max_tones"]:
        out.append("%d tones > %d" % (len(cols), DATA["max_tones"]))
    if any(c[:3] == (0, 0, 0) for c in cols):
        out.append("pure black outline")
    return out


def all_sets() -> list:
    return DATA["starting_set"] + DATA.get("first_batch", [])


def sheet(path: str) -> None:
    sc, pad = 3, 8
    sets = all_sets()
    lines = []
    for sp in sets:
        if sp["line"] not in lines:
            lines.append(sp["line"])
    w = (S * sc + pad) * 6 + pad
    h = (S * sc + pad) * len(lines) + pad
    bg = Image.new("RGBA", (w, h), (238, 230, 214, 255))
    for row, line in enumerate(lines):
        col = 0
        for sp in [s for s in sets if s["line"] == line]:
            for back in (False, True):
                im = Image.open(os.path.join(DST, "%s_%s.png" % (sp["id"], "back" if back else "front"))).convert("RGBA")
                im = im.resize((S * sc, S * sc), Image.NEAREST)
                bg.alpha_composite(im, (pad + col * (S * sc + pad), pad + row * (S * sc + pad)))
                col += 1
    bg.save(path)


def main(argv: list[str]) -> int:
    check = "--check" in argv
    bad = 0
    os.makedirs(DST, exist_ok=True)
    for sp in all_sets():
        for back in (False, True):
            path = os.path.join(DST, "%s_%s.png" % (sp["id"], "back" if back else "front"))
            if check:
                img = Image.open(path).convert("RGBA")
            else:
                img = render(sp, back)
                img.save(path)
            for p in problems(img):
                print("%s: %s" % (path, p))
                bad += 1
    if "--sheet" in argv:
        sheet(argv[argv.index("--sheet") + 1])
    return 1 if bad else 0


# --- Lines drawn from gen_lines.py body plans -----------------------------------------------
# Each gen_lines part keeps its exact outline (sampled from 56 to 64 px) and is lit as the
# ellipsoid of its bounding box, so the light, coloured outlines and textures match the hand-built
# kinds above. Body parts take the first element's material ("light" parts one tone brighter),
# "dark" parts the second element's material: 2 materials x 5 tones = 10 tones at most.
