def main() -> None:
    assert len(AREAS) == 25, len(AREAS)
    out = [HEADER]
    n = 0
    done = 0
    for title, items in AREAS:
        assert len(items) == 40, (title, len(items))
        out.append(f"\n## {title}\n")
        for it in items:
            n += 1
            mark = "[ ]"
            if it.startswith("[x] "):
                it = it[4:]
                mark = "[x]"
                done += 1
            out.append(f"{n}. {mark} {it}")
    out.append(f"\n---\n{done} von {n} Punkten umgesetzt.\n")
    path = Path(__file__).resolve().parents[2] / "docs" / "KAMPF_PLAN_1000.md"
    text = "\n".join(out) + "\n"
    if "--check" in sys.argv:
        # CI (ip-check job): the md must be what this tool writes, so no tick is set by hand
        # and no tick is lost in a merge.
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            sys.exit(f"{path} is out of date: run python3 tools/plan/plan_1000.py and commit it")
        print(f"{path}: up to date, {done} of {n} done")
        return
    path.write_text(text, encoding="utf-8")
    print(f"{path}: {n} points, {done} done")


if __name__ == "__main__":
    main()
